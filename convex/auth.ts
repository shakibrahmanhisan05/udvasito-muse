import { createClient, type GenericCtx } from "@convex-dev/better-auth";
import { convexAdapter } from "@convex-dev/better-auth";
import { betterAuth } from "better-auth";
import { internalMutationGeneric, makeFunctionReference } from "convex/server";
import { v } from "convex/values";
import type { DataModel } from "./schemaTypes";

/**
 * Better Auth + Convex component (ADR-003). Google is the only production
 * sign-in method; email+password exists ONLY for staging automated tests and
 * the production practice-area sign-in (P-10, D-R4) and stays disabled unless
 * BETTER_AUTH_EMAIL_ENABLED=1 in the Convex environment.
 *
 * HUMAN STEPS (RB-4): create the Google Cloud OAuth client (no billing) and
 * set GOOGLE_CLIENT_ID / GOOGLE_CLIENT_SECRET / BETTER_AUTH_SECRET /
 * BETTER_AUTH_URL in the Convex env. No credentials live in this repo.
 *
 * NOTE: `components.betterAuth` is normally imported from
 * convex/_generated/api after the first `npm run convex` codegen. The
 * equivalent component reference is constructed here so the repo
 * type-checks before any deployment exists (P0).
 */
function componentRef<T>(name: string): T {
  return makeFunctionReference(name) as unknown as T;
}

const betterAuthComponent = {
  adapter: {
    create: componentRef("betterAuth:adapter:create"),
    findOne: componentRef("betterAuth:adapter:findOne"),
    findMany: componentRef("betterAuth:adapter:findMany"),
    updateOne: componentRef("betterAuth:adapter:updateOne"),
    updateMany: componentRef("betterAuth:adapter:updateMany"),
    deleteOne: componentRef("betterAuth:adapter:deleteOne"),
    deleteMany: componentRef("betterAuth:adapter:deleteMany"),
    consumeOne: componentRef("betterAuth:adapter:consumeOne"),
    incrementOne: componentRef("betterAuth:adapter:incrementOne"),
  },
};

/**
 * The component's full generic surface is generated by Convex codegen; the
 * P0 surface we rely on is adapter() + registerRoutes(). The cast keeps the
 * repo type-checkable before the first deployment exists — after
 * `npm run convex` generates convex/_generated, this can be replaced by the
 * fully typed `components.betterAuth` reference.
 */
export type AuthComponent = {
  adapter: () => unknown;
  registerRoutes: (http: import("convex/server").HttpRouter, createAuthFn: (ctx: GenericCtx<DataModel>) => unknown) => void;
};

export const authComponent = (
  createClient as unknown as (component: unknown, config: unknown) => AuthComponent
)(betterAuthComponent, {
  authFunctions: {
    onCreate: makeFunctionReference("auth:onCreateAuthUser"),
    onUpdate: makeFunctionReference("auth:onUpdateAuthUser"),
    onDelete: makeFunctionReference("auth:onDeleteAuthUser"),
  },
});

/**
 * Auth-user lifecycle hooks. App profiles are created at onboarding
 * (profiles.completeOnboarding, P1) — these hooks intentionally do not
 * create profiles, so a Google account alone never becomes a member record
 * without name/DOB/phone and the 18+ gate (F-102).
 */
export const onCreateAuthUser = internalMutationGeneric({
  args: { doc: v.any() },
  handler: async () => {
    // No-op in P0 by design — see comment above.
  },
});
export const onUpdateAuthUser = internalMutationGeneric({
  args: { doc: v.any(), oldDoc: v.any() },
  handler: async () => {
    // No-op in P0 by design.
  },
});
export const onDeleteAuthUser = internalMutationGeneric({
  args: { doc: v.any() },
  handler: async () => {
    // Account deletion flow lands in P3 (F-603) via retention jobs.
  },
});

export function createAuth(ctx: GenericCtx<DataModel>) {
  const googleConfigured = Boolean(process.env.GOOGLE_CLIENT_ID && process.env.GOOGLE_CLIENT_SECRET);
  return betterAuth({
    baseURL: process.env.BETTER_AUTH_URL,
    secret: process.env.BETTER_AUTH_SECRET,
    database: convexAdapter(ctx as never, authComponent as never),
    socialProviders: googleConfigured
      ? {
          google: {
            clientId: process.env.GOOGLE_CLIENT_ID as string,
            clientSecret: process.env.GOOGLE_CLIENT_SECRET as string,
          },
        }
      : {},
    emailAndPassword: {
      enabled: process.env.BETTER_AUTH_EMAIL_ENABLED === "1",
      disableSignUp: false,
    },
  });
}
