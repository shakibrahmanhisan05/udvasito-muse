/**
 * DEP-09 intake evaluation → docs/intake-eval.md (roadmap P4 DoD).
 *
 * Runs the 40 fixture messages through (1) the rules parser alone and
 * (2) rules + the fixture Gemini responses merged by the REAL
 * mergeAiFields from convex/ai/gemini.ts, simulated exactly as
 * convex/intake.ts behaves: the AI is consulted only when a required
 * field (bloodGroup, units, hospitalId) is still missing after rules,
 * and it may only fill gaps. Run: npm run intake:eval
 * Exits non-zero when a roadmap target (≥60% rules-only, ≥85% with AI)
 * is missed, so the numbers in the doc are always the real ones.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { parseIntake } from "../convex/rules/intakeParser";
import { mergeAiFields, missingRequired, type AiIntakeFields } from "../convex/ai/gemini";
import {
  buildEvalRefData,
  loadIntakeCases,
  scoreFields,
  summarise,
  EVAL_FIELDS,
  type EvalField,
} from "./intake-eval-lib";

const refData = buildEvalRefData();
const hospitalNameById = new Map(refData.hospitals.map((h) => [h._id, h.nameEn]));
const cases = loadIntakeCases();
const aiFixtures = JSON.parse(
  readFileSync("tests/fixtures/intake-ai.json", "utf8"),
) as Record<string, AiIntakeFields>;

function runRulesOnly() {
  const results = new Map<string, Record<EvalField, boolean>>();
  for (const c of cases) {
    const parsed = parseIntake(c.text, c.lang === "bn" ? "bn" : "en", refData);
    results.set(c.id, scoreFields(c.expected, parsed.fields, hospitalNameById));
  }
  return summarise(cases, results);
}

function runRulesPlusAi() {
  const results = new Map<string, Record<EvalField, boolean>>();
  let aiCalls = 0;
  for (const c of cases) {
    const parsed = parseIntake(c.text, c.lang === "bn" ? "bn" : "en", refData);
    let fields = parsed.fields;
    if (missingRequired(fields).length > 0) {
      const fixture = aiFixtures[c.id];
      if (fixture) {
        aiCalls++;
        fields = mergeAiFields(fields, fixture, refData);
      }
    }
    results.set(c.id, scoreFields(c.expected, fields, hospitalNameById));
  }
  return { summary: summarise(cases, results), aiCalls };
}

const rules = runRulesOnly();
const { summary: withAi, aiCalls } = runRulesPlusAi();

const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
function fieldTable(s: typeof rules): string {
  const rows = EVAL_FIELDS.map(
    (f) => `| ${f} | ${s.perField[f].correct}/${s.perField[f].total} | ${pct(s.perField[f].accuracy)} |`,
  );
  return ["| Field | Correct | Accuracy |", "|---|---|---|", ...rows].join("\n");
}
function missList(s: typeof rules): string {
  const rows = s.perCase.filter((c) => c.wrong.length > 0);
  if (rows.length === 0) return "_None — every case fully correct._";
  return rows.map((c) => `- **${c.id}** (${c.correct}/${c.total}): ${c.wrong.join(", ")}`).join("\n");
}

const doc = `# Intake evaluation — DEP-09 (roadmap P4 Definition of Done)

_Generated by \`npm run intake:eval\` (scripts/intake-eval.ts) from
tests/fixtures/intake.jsonl + tests/fixtures/intake-ai.json. Do not edit
the numbers by hand — re-run the script._

## Headline results

| Pass | Fields correct | Accuracy | Roadmap target |
|---|---|---|---|
| Rules only | ${rules.correct}/${rules.total} | **${pct(rules.accuracy)}** | ≥ 60% |
| Rules + AI (fixture) | ${withAi.correct}/${withAi.total} | **${pct(withAi.accuracy)}** | ≥ 85% |

## Method

- **Corpus:** the DEP-09 set — 40 real-style messages (20 Bangla/Banglish,
  10 English, 10 pasted Facebook/WhatsApp-style posts) with expected
  fields, in \`tests/fixtures/intake.jsonl\`. The set is synthetic
  (written for this project, anonymised by construction — all names and
  numbers in it are fictional test values); member 3's DEP-09 delivery
  of real anonymised messages can replace it file-for-file.
- **Scoring:** 7 fields per case (280 slots): bloodGroup, component,
  units, hospital, area, neededBy, isDengue. A field scores 1 when
  correct, including correctly-empty (expected null and parsed null).
  neededBy is scored on the parser's coarser kinds: now→{now},
  today→{today, today_evening}, tomorrow→{tomorrow, tomorrow_morning,
  tomorrow_evening}, datetime→{day_after_tomorrow}. isDengue: the
  parser asserts true or stays silent (null); expected-false scores
  correct when the parser did not claim dengue, because the form's
  dengue flag defaults off — null and false are the same product state.
- **RefData** is built from the same sources the server uses:
  data/hospitals.csv (names + aliases) and data/places.json. A
  hospital's area is its upazila name, supplied only for metro-thana
  hospitals (the server does the same in intake.refData).
- **Rules + AI pass:** no live Gemini key exists in this environment,
  so the AI side uses hand-authored fixture responses
  (tests/fixtures/intake-ai.json) — one per message, written from the
  message text alone under the system prompt's "null when not clearly
  stated — never guess" rule, in the specs §6.10 schema. The merge is
  NOT simulated: it runs the production \`mergeAiFields\` from
  convex/ai/gemini.ts, and the AI is consulted only when a required
  field (bloodGroup, units, hospitalId) is missing after rules —
  exactly as convex/intake.ts behaves. The AI was consulted for
  ${aiCalls} of 40 messages. Read the with-AI number with the fixture
  caveat in mind; the action itself (redaction, quota, logging,
  fallback) is covered end-to-end with a mocked Gemini fetch in
  tests/p4.test.ts.

## Per-field accuracy — rules only (${rules.correct}/${rules.total} = ${pct(rules.accuracy)})

${fieldTable(rules)}

### Rules-only misses by case

${missList(rules)}

## Per-field accuracy — rules + AI (${withAi.correct}/${withAi.total} = ${pct(withAi.accuracy)})

${fieldTable(withAi)}

### Rules + AI misses by case

${missList(withAi)}

## Reading the area misses

Every remaining miss is the \`area\` field, and every one is the same
phenomenon: the fixture names the **neighbourhood** a family would say
(Agrabad, Andarkilla, Mehedibag), while the parser names the **thana**
from the places data (Double Mooring, Kotwali) — the neighbourhood lies
inside that thana, so the location is right and the label differs.
The places dataset (582 rows) contains thana/upazila names only; the
three neighbourhood names appear in no reference data the parser is
allowed to use (hospital matching is refData-only by contract, and the
neighbourhoods occur only inside hospital street addresses). Two cases
(en-10, bn-08, National Hospital) invert the same gap: the fixture
expects no area, the parser offers the hospital's thana (Kotwali).

Fix path (data, not code): add neighbourhood-level rows (Agrabad,
Andarkilla, Mehedibag, …) to the places reference data with their
Bangla names — a member-3 data task alongside DEP-08/DEP-09. The
parser picks them up automatically via refData.areas.
`;

writeFileSync("docs/intake-eval.md", doc);
console.log(`rules-only: ${rules.correct}/${rules.total} = ${pct(rules.accuracy)} (target ≥ 60%)`);
console.log(`rules+AI:   ${withAi.correct}/${withAi.total} = ${pct(withAi.accuracy)} (target ≥ 85%, AI consulted ${aiCalls}/40)`);
console.log("wrote docs/intake-eval.md");
if (rules.accuracy < 0.6 || withAi.accuracy < 0.85) {
  console.error("TARGET MISSED");
  process.exit(1);
}
